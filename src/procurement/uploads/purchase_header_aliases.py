"""
procurement.uploads.purchase_header_aliases

고객 기관이 매달 내려받는 **구매실적 원본**의 머리글을 표준 항목명으로
옮깁니다.

왜 필요한가
===========
기관이 회계 시스템에서 받는 파일의 칸 이름과 이 시스템의 표준 항목명이
다릅니다. 대응이 없으면 담당자가 **매달 원본을 열어 머리글을 고쳐야** 하고,
고치는 순간 그것은 기관이 내려받은 원본이 아니게 됩니다. 2,305행을 매달
손으로 옮기다 틀리면 실적이 틀립니다.

기업정보(명단) 업로드에는 같은 장치가 이미 있습니다
(:mod:`procurement.uploads.company_header_aliases`). 구매실적에만 없어서
실제 원본이 통째로 거절됐습니다(STEP 157-㉠).

⛔ 짐작하지 않습니다
====================
**실제로 받아 본 파일에서 확인한 이름만** 적습니다. 아래 두 가지는
2026-09-10 고객 PC 의 구매실적 원본에서 확인한 것입니다.

다음은 하지 않습니다.

- 글자가 비슷하다고 짝지어 주기 (업체명 · 상호 · 거래처 …)
- 뜻을 미루어 짐작하기
- 동의어 사전을 임의로 넓히기

다른 기관·다른 회계 시스템의 파일을 실제로 확보하면, 그 파일을 확인한 뒤
여기에 **따로** 더합니다.
"""

from __future__ import annotations

from types import MappingProxyType
from typing import Final

#: 고객 구매실적 원본 머리글 → 표준 항목명.
#:
#: 실측 대응(2026-09-10 · STEP 157-㉠ · 원본 2,305행):
#:
#: ==================== ====================
#: 원본                 표준 항목명
#: ==================== ====================
#: ``거래처명``          ``기업명``
#: ``사업자번호``        ``사업자등록번호``
#: ==================== ====================
#:
#: ``결의일자`` · ``신고기준일`` · ``계`` · ``적요`` · ``예산과목`` 은 이름이
#: **같아서** 여기 없습니다. 대응이 필요 없습니다.
#:
#: ⛔ ``공급가액`` · ``세액`` 은 표준 항목이 아닙니다. 실적 금액은 부가세를
#: 포함한 ``계`` 이며, 공급가액을 금액으로 바꿔치기하지 않습니다.
PURCHASE_HEADER_ALIASES: Final[MappingProxyType[str, str]] = MappingProxyType(
    {
        "거래처명": "기업명",
        "사업자번호": "사업자등록번호",
    }
)
